// ---------------------------------------------------------------------------
// Pixel helpers
// ---------------------------------------------------------------------------
void HudTexture::setPixel(int x, int y, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (x < 0 || x >= w_ || y < 0 || y >= h_) return;
    uint8_t* p = pixels_.data() + (y * w_ + x) * 4;
    p[0] = r; p[1] = g; p[2] = b; p[3] = a;
}

void HudTexture::fillRect(int x, int y, int rw, int rh,
                           uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    int x1 = std::clamp(x,      0, w_);
    int y1 = std::clamp(y,      0, h_);
    int x2 = std::clamp(x + rw, 0, w_);
    int y2 = std::clamp(y + rh, 0, h_);
    for (int py = y1; py < y2; ++py)
        for (int px = x1; px < x2; ++px) {
            uint8_t* p = pixels_.data() + (py * w_ + px) * 4;
            p[0] = r; p[1] = g; p[2] = b; p[3] = a;
        }
}

void HudTexture::drawChar(int x, int y, char c, int scale,
                           uint8_t r, uint8_t g, uint8_t b) {
    int idx = (uint8_t)c - 32;
    if (idx < 0 || idx >= 95) idx = 0;
    const uint8_t* bmp = kFont[idx];
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = bmp[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80u >> col))
                fillRect(x + col * scale, y + row * scale, scale, scale, r, g, b);
        }
    }
}

void HudTexture::drawText(int x, int y, const char* s, int scale,
                           uint8_t r, uint8_t g, uint8_t b) {
    int cx = x;
    for (; *s; ++s) {
        drawChar(cx, y, *s, scale, r, g, b);
        cx += 9 * scale;   // 8px glyph + 1px kerning gap
    }
}

// ---------------------------------------------------------------------------
// Init / resize / destroy
// ---------------------------------------------------------------------------
bool HudTexture::init(int w, int h) {
    w_ = std::max(w, 1);
    h_ = std::max(h, 1);
    pixels_.assign((size_t)w_ * h_ * 4, 0);

    glGenTextures(1, &tex_);
    glBindTexture(GL_TEXTURE_2D, tex_);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, w_, h_, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
    return true;
}

void HudTexture::resize(int w, int h) {
    w = std::max(w, 1);
    h = std::max(h, 1);
    if (w == w_ && h == h_) return;
    w_ = w; h_ = h;
    pixels_.assign((size_t)w_ * h_ * 4, 0);

    glBindTexture(GL_TEXTURE_2D, tex_);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, w_, h_, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
    glBindTexture(GL_TEXTURE_2D, 0);
}

void HudTexture::destroy() {
    if (tex_) { glDeleteTextures(1, &tex_); tex_ = 0; }
    pixels_.clear();
    w_ = h_ = 0;
}

// ---------------------------------------------------------------------------
// Event handlers
// ---------------------------------------------------------------------------
void HudTexture::onLowFuel(const LowFuelEvent&) {
    lowFuel_      = true;
    warningTimer_ = 3.0f;
}
void HudTexture::onFuelDepleted(const FuelDepletedEvent&) {
    fuelDepleted_ = true;
}

// ---------------------------------------------------------------------------
// Per-frame update
// ---------------------------------------------------------------------------
void HudTexture::update(entt::registry& reg, entt::entity player, float dt) {
    if (tex_ == 0 || w_ < 1 || h_ < 1) return;

    // Clear to fully transparent
    std::fill(pixels_.begin(), pixels_.end(), 0);

    warningTimer_ = std::max(0.0f, warningTimer_ - dt);

    if (player == entt::null || !reg.valid(player)) {
        glBindTexture(GL_TEXTURE_2D, tex_);
        glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, w_, h_,
                        GL_RGBA, GL_UNSIGNED_BYTE, pixels_.data());
        glBindTexture(GL_TEXTURE_2D, 0);
        return;
    }

    const Fuel*            fuel  = reg.try_get<Fuel>(player);
    const DerivedCarStats* stats = reg.try_get<DerivedCarStats>(player);
    const Velocity*        vel   = reg.try_get<Velocity>(player);

    // -----------------------------------------------------------------------
    // Layout: top-right block
    // -----------------------------------------------------------------------
    constexpr int kScale    = 2;          // font scale: 16×16 px per glyph
    constexpr int kGlyph    = 9 * kScale; // pixels per character column
    constexpr int kLineH    = 8 * kScale + 4;
    constexpr int kMarginR  = 16;
    constexpr int kMarginT  = 16;

    // Background panel width: enough for ~22 chars + margins
    constexpr int kPanelW   = kGlyph * 22 + 12;
    int panelX = w_ - kPanelW - kMarginR;
    int panelY = kMarginT;

    int tx = panelX;
    int ty = panelY;

    char buf[128];

    // Line 1 — speed
    if (vel) {
        float speed = glm::length(vel->linear);
        std::snprintf(buf, sizeof(buf), "SPEED: %.1f m/s", speed);
        drawText(tx, ty, buf, kScale, 255, 255, 255);
    }
    ty += kLineH;

    // Line 2 — top speed + power
    if (stats) {
        std::snprintf(buf, sizeof(buf), "TOP: %.0f  POWER: %.0f",
                      stats->topSpeed, stats->power);
        drawText(tx, ty, buf, kScale, 255, 255, 255);
    }
    ty += kLineH;

    // Line 3 — fuel bar
    if (fuel) {
        drawText(tx, ty, "FUEL:", kScale, 255, 255, 255);

        float ratio   = fuel->ratio();
        int   barX    = tx + kGlyph * 6;
        int   barY    = ty + 2;
        int   barW    = kGlyph * 10;
        int   barH    = 8 * kScale - 2;

        // Fill
        int fillW = (int)(barW * ratio);
        uint8_t fr = (ratio > 0.5f) ? 50  : (ratio > 0.25f) ? 220 : 220;
        uint8_t fg = (ratio > 0.5f) ? 200 : (ratio > 0.25f) ? 130 : 50;
        uint8_t fb = (ratio > 0.5f) ? 80  : 40;
        if (fillW > 0)
            fillRect(barX, barY, fillW, barH, fr, fg, fb, 230);

        // Border
        for (int bx = barX; bx < barX + barW; ++bx) {
            setPixel(bx, barY,          180, 180, 180);
            setPixel(bx, barY + barH-1, 180, 180, 180);
        }
        for (int by = barY; by < barY + barH; ++by) {
            setPixel(barX,         by, 180, 180, 180);
            setPixel(barX + barW-1,by, 180, 180, 180);
        }
    }
    ty += kLineH;

    // Line 4 — fuel warnings
    if (fuelDepleted_) {
        drawText(tx, ty, "OUT OF FUEL", kScale, 255, 60, 60);
    } else if (lowFuel_ && warningTimer_ > 0.0f) {
        // Blink at ~4 Hz using warningTimer_
        if (std::fmod(warningTimer_, 0.5f) > 0.25f)
            drawText(tx, ty, "LOW FUEL!", kScale, 255, 160, 30);
    }

    // -----------------------------------------------------------------------
    // Centre-screen GAME OVER overlay
    // -----------------------------------------------------------------------
    if (fuelDepleted_) {
        const char* msg = "GAME  OVER";
        constexpr int kBig  = 4;
        constexpr int kBigG = 9 * kBig;
        int msgW = (int)(__builtin_strlen(msg)) * kBigG;
        int msgX = (w_ - msgW) / 2;
        int msgY = (h_ - 8 * kBig) / 2;
        drawText(msgX, msgY, msg, kBig, 255, 60, 60);
    }

    // Upload to GPU
    glBindTexture(GL_TEXTURE_2D, tex_);
    glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, w_, h_,
                    GL_RGBA, GL_UNSIGNED_BYTE, pixels_.data());
    glBindTexture(GL_TEXTURE_2D, 0);
}
